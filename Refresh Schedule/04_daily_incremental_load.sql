-- ============================================================
-- GA4 → Power BI: Daily Incremental Load
-- ============================================================
-- This is the PRODUCTION pattern — the entire body of the BigQuery
-- Scheduled Query is this single CALL. All logic lives in the
-- procedures created by BigQuery/02_pipeline_procedures.sql.
--
-- What it does each day:
--   • computes "today" in the GA4 property's own timezone (not UTC),
--     because GA4 names events_YYYYMMDD tables by the property's date
--   • reprocesses the last 3 COMPLETE days (not just yesterday), which
--     picks up late-arriving events and self-heals after a missed or
--     failed run
--   • replaces those days in fact_events inside a transaction, so
--     re-running the job never creates duplicates
--   • rebuilds the dimensions and refreshes the views
--
-- Replace the timezone with the property's reporting time zone
-- (GA4: Admin → Property settings → Reporting time zone), as an IANA
-- name, e.g. 'America/Los_Angeles', 'Europe/Berlin'.
--
-- Not required to explore this repo's demo, since the sample dataset
-- is static historical data (it simply finds no new days).
--
-- To deploy: BigQuery console → paste the CALL below → run it once to
-- confirm it works → Schedule → Create new scheduled query → daily,
-- timed after GA4's daily export typically lands. Scheduled queries
-- are not available in BigQuery Sandbox, as far as I know — enable
-- billing on the project first (check Google's docs for current limits).
-- ============================================================

CALL `<PROJECT_ID>.<DATASET>.run_daily_refresh`('America/Los_Angeles', 3);
